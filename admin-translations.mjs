export function createAdminTranslator(locale = 'zh-CN') {
  const active = adminCopy[locale] || adminCopy['zh-CN'];
  const fallback = adminCopy.en;
  return (key, values = {}) => Object.entries(values).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
    active[key] ?? fallback[key] ?? key,
  );
}
